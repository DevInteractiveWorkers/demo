// app/api/request/route.ts

import { NextRequest, NextResponse } from "next/server";
import { sendEmail } from "@/lib/sendEmail";

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();

    const {
      name,
      lastName,
      email,
      phone,
      companyName,
      linkedinUrl,
      position,
      inquiry,
      submittedAt,
      timezone,
    } = body;

    if (
      !name ||
      !lastName ||
      !email ||
      !phone ||
      !companyName ||
      !linkedinUrl ||
      !position ||
      !inquiry
    ) {
      return NextResponse.json(
        {
          success: false,
          message: "Missing required fields.",
        },
        { status: 400 },
      );
    }

    const positions = Array.isArray(position) ? position.join(", ") : position;

    const html = `
<!DOCTYPE html>
<html>
<head>
<meta charset="UTF-8" />
<style>

body{
    margin:0;
    padding:32px;
    background:#f5f5f5;
    font-family:Arial,Helvetica,sans-serif;
    color:#222;
}

.container{
    max-width:800px;
    margin:auto;
    background:#fff;
    border-radius:12px;
    overflow:hidden;
    box-shadow:0 4px 14px rgba(0,0,0,.08);
}

.header{
    background:#c1272d;
    color:#fff;
    padding:24px;
}

.header h2{
    text-align:center;
    margin:0;
}

.section{
    padding:28px;
}

table{
    width:100%;
    border-collapse:collapse;
}

td{
    padding:10px;
    border-bottom:1px solid #eee;
    vertical-align:top;
}

.label{
    width:200px;
    font-weight:bold;
    color:#444;
}

.description{
    margin-top:12px;
    border:1px solid #ddd;
    background:#fafafa;
    border-radius:8px;
    padding:16px;
    white-space:pre-wrap;
}

.footer{
    background:#fafafa;
    padding:20px;
    color:#666;
    font-size:13px;
}

.logo{
    max-width:100%;
    height:auto;
    display:block;
    margin:auto;
}

</style>
</head>

<body>

<div class="container">

<div class="header">

<img
    src="https://assets.cdn.filesafe.space/dtfCxBE6SEYaCMFTlgu5/media/6a4e72d7708c41d4dff4d1de.png"
    alt="Interactive Workers"
    width="260"
    class="logo"
/>

</div>

<div class="section">

<h3>Lead Information</h3>

<table>

<tr>
<td class="label">First Name</td>
<td>${name}</td>
</tr>

<tr>
<td class="label">Last Name</td>
<td>${lastName}</td>
</tr>

<tr>
<td class="label">Email</td>
<td>${email}</td>
</tr>

<tr>
<td class="label">Phone</td>
<td>${phone}</td>
</tr>

<tr>
<td class="label">Company</td>
<td>${companyName}</td>
</tr>

<tr>
<td class="label">LinkedIn</td>
<td>
<a href="${linkedinUrl}">
${linkedinUrl}
</a>
</td>
</tr>

<tr>
<td class="label">Position(s) of Interest</td>
<td>${positions}</td>
</tr>

</table>

<h3 style="margin-top:32px;">Inquiry</h3>

<div class="description">
${inquiry}
</div>

<h3 style="margin-top:32px;">Technical Information</h3>

<table>

<tr>
<td class="label">Timezone</td>
<td>${timezone || "-"}</td>
</tr>

<tr>
<td class="label">Submitted At</td>
<td>${submittedAt || new Date().toISOString()}</td>
</tr>

</table>

</div>

<div class="footer">
This email was automatically generated by the Interactive Workers Demo Request Form.
</div>

</div>

</body>
</html>
`;

    await sendEmail({
      from: `"Interactive Workers Demo" <${process.env.NODEMAILER_USER}>`,
      to: process.env.NODEMAILER_USER || process.env.NODEMAILER_USER!,
      subject: `[Demo Request] ${companyName} • ${name} ${lastName}`,
      html,
    });

    return NextResponse.json({
      success: true,
    });
  } catch (error) {
    console.error(error);

    return NextResponse.json(
      {
        success: false,
        message: "Unable to submit demo request.",
      },
      { status: 500 },
    );
  }
}
