// app/api/request/route.ts

import { NextRequest, NextResponse } from "next/server";
import { sendEmail } from "@/lib/sendEmail";
import { renderFormEmail } from "@/lib/email-template";

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();

    const {
      name,
      lastName,
      email,
      phone,
      companyName,
      linkedinUrl,
      position,
      inquiry,
      submittedAt,
      timezone,
    } = body;

    if (
      !name ||
      !lastName ||
      !email ||
      !phone ||
      !companyName ||
      !linkedinUrl ||
      !position ||
      !inquiry
    ) {
      return NextResponse.json(
        {
          success: false,
          message: "Missing required fields.",
        },
        { status: 400 },
      );
    }

    const positions = Array.isArray(position) ? position.join(", ") : position;

    const html = renderFormEmail({
      logoAlt: "Interactive Workers",
      labelWidth: 200,
      infoTitle: "Lead Information",
      info: [
        ["First Name", name],
        ["Last Name", lastName],
        ["Email", email],
        ["Phone", phone],
        ["Company", companyName],
        ["LinkedIn", `<a href="${linkedinUrl}">${linkedinUrl}</a>`],
        ["Position(s) of Interest", positions],
      ],
      messageTitle: "Inquiry",
      message: inquiry,
      technical: [
        ["Timezone", timezone || "-"],
        ["Submitted At", submittedAt || new Date().toISOString()],
      ],
      footer:
        "This email was automatically generated by the Interactive Workers Demo Request Form.",
    });

    await sendEmail({
      from: `"Interactive Workers Demo" <${process.env.NODEMAILER_USER}>`,
      to: process.env.NODEMAILER_USER!,
      subject: `[Demo Request] ${companyName} • ${name} ${lastName}`,
      html,
    });

    return NextResponse.json({
      success: true,
    });
  } catch (error) {
    console.error(error);

    return NextResponse.json(
      {
        success: false,
        message: "Unable to submit demo request.",
      },
      { status: 500 },
    );
  }
}
