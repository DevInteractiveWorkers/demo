// app/api/support/route.ts

import { NextRequest, NextResponse } from "next/server";
import { sendEmail } from "@/lib/sendEmail";

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();

    const {
      name,
      email,
      issue,
      description,
      url,
      currentUrl,
      referrer,
      userAgent,
      submittedAt,
      timezone,
      screenResolution,
      viewport,
    } = body;

    if (!name || !email || !issue || !description) {
      return NextResponse.json(
        {
          success: false,
          message: "Missing required fields.",
        },
        { status: 400 },
      );
    }

    const html = `
<!DOCTYPE html>
<html>
<head>
<meta charset="UTF-8" />
<style>
body{
    margin:0;
    padding:32px;
    background:#f5f5f5;
    font-family:Arial,Helvetica,sans-serif;
    color:#222;
}

.container{
    max-width:800px;
    margin:auto;
    background:#fff;
    border-radius:12px;
    overflow:hidden;
    box-shadow:0 4px 14px rgba(0,0,0,.08);
}

.header{
    background:#c1272d;
    color:#fff;
    padding:24px;
}

.header h2{
    text-align: center;
    margin:0;
}

.section{
    padding:28px;
}

table{
    width:100%;
    border-collapse:collapse;
}

td{
    padding:10px;
    border-bottom:1px solid #eee;
    vertical-align:top;
}

.label{
    width:180px;
    font-weight:bold;
    color:#444;
}

.description{
    margin-top:12px;
    border:1px solid #ddd;
    background:#fafafa;
    border-radius:8px;
    padding:16px;
    white-space:pre-wrap;
}

.footer{
    background:#fafafa;
    padding:20px;
    color:#666;
    font-size:13px;
}

.logo{
    max-width:100%;
    height:auto;
    display:block;
    margin:auto;
}

</style>
</head>

<body>

<div class="container">

<div class="header">
<img
    src="https://assets.cdn.filesafe.space/dtfCxBE6SEYaCMFTlgu5/media/6a4e72d7708c41d4dff4d1de.png"
    alt="Logo"
    width="260"
    class="logo"
/>
<h2>🛠 New Support Request</h2>
</div>

<div class="section">

<h3>User Information</h3>

<table>

<tr>
<td class="label">Name</td>
<td>${name}</td>
</tr>

<tr>
<td class="label">Email</td>
<td>${email}</td>
</tr>

<tr>
<td class="label">Issue Type</td>
<td>${issue}</td>
</tr>

<tr>
<td class="label">Related URL</td>
<td>${url || "Not provided"}</td>
</tr>

</table>

<h3 style="margin-top:32px;">Description</h3>

<div class="description">
${description}
</div>

<h3 style="margin-top:32px;">Technical Information</h3>

<table>

<tr>
<td class="label">Current Page</td>
<td>${currentUrl || "-"}</td>
</tr>

<tr>
<td class="label">Referrer</td>
<td>${referrer || "-"}</td>
</tr>

<tr>
<td class="label">Browser</td>
<td>${userAgent || "-"}</td>
</tr>

<tr>
<td class="label">Timezone</td>
<td>${timezone || "-"}</td>
</tr>

<tr>
<td class="label">Screen Resolution</td>
<td>${screenResolution || "-"}</td>
</tr>

<tr>
<td class="label">Viewport</td>
<td>${viewport || "-"}</td>
</tr>

<tr>
<td class="label">Submitted At</td>
<td>${submittedAt || new Date().toISOString()}</td>
</tr>

</table>

</div>

<div class="footer">
This email was automatically generated by the Interactive Workers Support Form.
</div>

</div>

</body>
</html>
`;

    await sendEmail({
      from: `"Interactive Workers Support" <${process.env.NODEMAILER_USER}>`,
      to: process.env.NODEMAILER_USER || process.env.NODEMAILER_USER!,
      subject: `[Support] ${issue} • ${name}`,
      html,
    });

    return NextResponse.json({
      success: true,
    });
  } catch (error) {
    console.error(error);

    return NextResponse.json(
      {
        success: false,
        message: "Unable to submit support request.",
      },
      { status: 500 },
    );
  }
}
