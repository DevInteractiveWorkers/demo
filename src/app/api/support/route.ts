// app/api/support/route.ts

import { NextRequest, NextResponse } from "next/server";
import { sendEmail } from "@/lib/sendEmail";
import { renderFormEmail } from "@/lib/email-template";

export async function POST(req: NextRequest) {
  try {
    const body = await req.json();

    const {
      name,
      email,
      issue,
      description,
      url,
      currentUrl,
      referrer,
      userAgent,
      submittedAt,
      timezone,
      screenResolution,
      viewport,
    } = body;

    if (!name || !email || !issue || !description) {
      return NextResponse.json(
        {
          success: false,
          message: "Missing required fields.",
        },
        { status: 400 },
      );
    }

    const html = renderFormEmail({
      logoAlt: "Logo",
      headerTitle: "🛠 New Support Request",
      labelWidth: 180,
      infoTitle: "User Information",
      info: [
        ["Name", name],
        ["Email", email],
        ["Issue Type", issue],
        ["Related URL", url || "Not provided"],
      ],
      messageTitle: "Description",
      message: description,
      technical: [
        ["Current Page", currentUrl || "-"],
        ["Referrer", referrer || "-"],
        ["Browser", userAgent || "-"],
        ["Timezone", timezone || "-"],
        ["Screen Resolution", screenResolution || "-"],
        ["Viewport", viewport || "-"],
        ["Submitted At", submittedAt || new Date().toISOString()],
      ],
      footer:
        "This email was automatically generated by the Interactive Workers Support Form.",
    });

    await sendEmail({
      from: `"Interactive Workers Support" <${process.env.NODEMAILER_USER}>`,
      to: process.env.NODEMAILER_USER!,
      subject: `[Support] ${issue} • ${name}`,
      html,
    });

    return NextResponse.json({
      success: true,
    });
  } catch (error) {
    console.error(error);

    return NextResponse.json(
      {
        success: false,
        message: "Unable to submit support request.",
      },
      { status: 500 },
    );
  }
}
